-- Schema for the embedded H2 database (Oracle mode). The same DDL works on Oracle 12c or newer:
-- run this script (and data.sql) by hand in your Oracle schema when you use the "oracle" profile.
CREATE TABLE sandwiches (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR2(100) NOT NULL,
    description VARCHAR2(500),
    category    VARCHAR2(50)  NOT NULL,
    base_price  NUMBER(6, 2)  NOT NULL,
    CONSTRAINT uq_sandwiches_name UNIQUE (name)
);

CREATE TABLE abis_courses (
    id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(200) NOT NULL,
    CONSTRAINT uq_abis_courses_title UNIQUE (title)
);

CREATE TABLE abis_persons (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR2(100) NOT NULL,
    last_name  VARCHAR2(100) NOT NULL,
    CONSTRAINT uq_abis_persons_name UNIQUE (first_name, last_name)
);

CREATE TABLE sandwich_orders (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date  DATE NOT NULL,
    course_id   INT  NOT NULL,
    total_price NUMBER(8, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_orders_course FOREIGN KEY (course_id) REFERENCES abis_courses (id),
    CONSTRAINT uq_orders_date_course UNIQUE (order_date, course_id)
);

CREATE TABLE sandwich_order_details (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INT NOT NULL,
    sandwich_id   INT NOT NULL,
    person_id     INT NOT NULL,
    amount        NUMBER(1) NOT NULL,
    bread_type    VARCHAR2(10) NOT NULL,
    vegetables    NUMBER(1) NOT NULL,
    order_comment VARCHAR2(200),
    CONSTRAINT fk_details_order    FOREIGN KEY (order_id)    REFERENCES sandwich_orders (id),
    CONSTRAINT fk_details_sandwich FOREIGN KEY (sandwich_id) REFERENCES sandwiches (id),
    CONSTRAINT fk_details_person   FOREIGN KEY (person_id)   REFERENCES abis_persons (id)
);
